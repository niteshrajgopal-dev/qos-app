export const STOREFRONTS_COPY: Record<StaffLocale, Record<StorefrontsCopyKey, string>> = {
  en: EN,
  ar: AR,
};

export function storefrontsCopy(
  locale: StaffLocale,
  key: StorefrontsCopyKey,
  values: Record<string, string | number> = {},
) {
  return Object.entries(values).reduce<string>(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    STOREFRONTS_COPY[locale][key],
  );
}

/** Latin digits in both locales, matching the rest of the staff portal. */
export function formatStorefrontDateTime(locale: StaffLocale, value: string | Date) {
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-AE" : "en-AE", {
    dateStyle: "medium",
    timeStyle: "short",
    numberingSystem: "latn",
  }).format(value instanceof Date ? value : new Date(value));
}
