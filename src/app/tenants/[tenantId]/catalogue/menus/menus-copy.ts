export const MENUS_COUNT_COPY: Record<StaffLocale, Record<MenusCountKey, StaffCountForms>> = {
  en: EN_COUNTS,
  ar: AR_COUNTS,
};

const PLURAL_RULES: Record<StaffLocale, Intl.PluralRules> = {
  en: new Intl.PluralRules("en"),
  ar: new Intl.PluralRules("ar"),
};

export function menusCount(
  locale: StaffLocale,
  key: MenusCountKey,
  count: number,
  values: Record<string, string | number> = {},
) {
  const forms = MENUS_COUNT_COPY[locale][key];
  const template = forms[PLURAL_RULES[locale].select(count)] ?? forms.other;
  return Object.entries({ ...values, count }).reduce<string>(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

function localeTag(locale: StaffLocale) {
  return locale === "ar" ? "ar-AE" : "en-AE";
}

/** Latin digits in both locales, matching the rest of the staff portal. */
export function formatMenuDate(locale: StaffLocale, value: string | Date) {
  return new Intl.DateTimeFormat(localeTag(locale), {
    dateStyle: "medium",
    numberingSystem: "latn",
  }).format(new Date(value));
}

export function formatMenuTime(locale: StaffLocale, value: string | Date) {
  return new Intl.DateTimeFormat(localeTag(locale), {
    timeStyle: "short",
    numberingSystem: "latn",
  }).format(new Date(value));
}

export function formatMenuPrice(locale: StaffLocale, amountMinor: number, currency: string) {
  return new Intl.NumberFormat(localeTag(locale), {
    style: "currency",
    currency,
    numberingSystem: "latn",
  }).format(amountMinor / 100);
}
