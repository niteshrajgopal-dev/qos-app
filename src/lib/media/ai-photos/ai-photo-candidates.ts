/**
 * Fails an unfinished request inside the caller's tenant transaction: its
 * upload grant is closed and the asset records why. A stored candidate is
 * never downgraded; it is returned unchanged.
 */
export async function failAiPhotoAssetInTx(
  tx: DbTransaction,
  tenantId: string,
  assetId: string,
  failure: AiPhotoFailure,
  actor: AiPhotoActor,
) {
  const [asset] = await tx
    .select()
    .from(catalogueMediaAssets)
    .where(and(eq(catalogueMediaAssets.tenantId, tenantId), eq(catalogueMediaAssets.id, assetId)))
    .limit(1)
    .for("update");
  if (!asset || asset.status !== "pending_upload") {
    return asset ?? null;
  }

  await tx
    .update(catalogueMediaUploadGrants)
    .set({ status: "expired" })
    .where(
      and(
        eq(catalogueMediaUploadGrants.tenantId, tenantId),
        eq(catalogueMediaUploadGrants.assetId, asset.id),
        eq(catalogueMediaUploadGrants.status, "pending"),
      ),
    );

  const { failureCode, providerOutcome, providerDiagnostics } = failure;
  const evidence = {
    ...(providerOutcome ? { providerOutcome } : {}),
    ...(providerDiagnostics ? { providerDiagnostics } : {}),
  };
  const [failed] = await tx
    .update(catalogueMediaAssets)
    .set({
      status: "failed",
      failureReason: failure.message,
      generationMetadata: { ...metadataOf(asset), failureCode, ...evidence },
      updatedAt: new Date(),
    })
    .where(eq(catalogueMediaAssets.id, asset.id))
    .returning();

  await recordTenantAuditEventInTx(tx, {
    tenantId,
    actorSubject: actor.subject,
    actorClass: actor.actorClass,
    action: "catalogue.media.ai_photo_failed",
    entityType: "catalogue_media_asset",
    entityPublicId: asset.publicId,
    changeSummary: { failureCode, ...evidence },
  });
  return failed!;
}

async function markGenerationFailed(
  db: DbClient,
  caller: AiPhotoCaller,
  assetId: string,
  failure: AiPhotoFailure,
) {
  return withTenantContext(db, caller.tenantId, (tx) =>
    failAiPhotoAssetInTx(tx, caller.tenantId, assetId, failure, actorOf(caller)),
  );
}

export const NOT_STARTED_IN_TIME_MESSAGE = "No worker started this photo in time. Nothing was generated or charged.";

function isStaleQueuedRequest(
  asset: typeof catalogueMediaAssets.$inferSelect,
  config: AiPhotoConfig,
  now: Date,
) {
  return (
    asset.status === "pending_upload" &&
    metadataOf(asset).executionMode === "queued_worker" &&
    now.getTime() - asset.createdAt.getTime() >= config.queuedStaleMs
  );
}

/**
 * Closes a queued request that no worker ever claimed: the job is cancelled,
 * the asset fails as never started and its spend is returned. A job a worker
 * has claimed is left to the worker, however old. False when nothing changed.
 */
async function cancelStaleQueuedRequestInTx(
  tx: DbTransaction,
  tenantId: string,
  asset: typeof catalogueMediaAssets.$inferSelect,
  actor: AiPhotoActor,
) {
  const [job] = await tx
    .select({ publicId: aiJobs.publicId })
    .from(aiJobs)
    .where(
      and(
        eq(aiJobs.tenantId, tenantId),
        eq(aiJobs.jobKind, AI_PHOTO_JOB_KIND),
        eq(aiJobs.mediaAssetId, asset.id),
      ),
    )
    .limit(1);
  if (
    !job ||
    !(await cancelUnclaimedAiJobInTx(tx, {
      jobPublicId: job.publicId,
      code: "not_started_in_time",
      message: NOT_STARTED_IN_TIME_MESSAGE,
    }))
  ) {
    return false;
  }

  await failAiPhotoAssetInTx(
    tx,
    tenantId,
    asset.id,
    { failureCode: "not_started_in_time", message: NOT_STARTED_IN_TIME_MESSAGE },
    actor,
  );
  const [reservation] = await tx
    .select({ publicId: aiSpendReservations.publicId })
    .from(aiSpendReservations)
    .where(
      and(
        eq(aiSpendReservations.tenantId, tenantId),
        eq(aiSpendReservations.path, AI_PHOTO_SPEND_PATH),
        eq(aiSpendReservations.subjectType, AI_PHOTO_SPEND_SUBJECT),
        eq(aiSpendReservations.subjectPublicId, asset.publicId),
        eq(aiSpendReservations.state, "reserved"),
        isNull(aiSpendReservations.dispatchedAt),
      ),
    )
    .limit(1);
  if (reservation) {
    await releaseUnstartedAiSpend(tx, { tenantId, reservationPublicId: reservation.publicId });
  }
  return true;
}

/** Re-encodes provider output: rejects anything that is not a decodable image and strips metadata. */
export async function normalizeGeneratedImage(bytes: Buffer) {
  const media = readMediaConfig();
  try {
    const output = await sharp(bytes, {
      failOn: "error",
      limitInputPixels: media.maxPixelDimension * media.maxPixelDimension,
    })
      .rotate()
      .resize({
        width: MAX_OUTPUT_DIMENSION,
        height: MAX_OUTPUT_DIMENSION,
        fit: "inside",
        withoutEnlargement: true,
      })
      .jpeg({ quality: 88, mozjpeg: true })
      .toBuffer();
    if (output.byteLength > media.maxUploadBytes) {
      throw new Error("too large");
    }
    return output;
  } catch {
    throw new AiPhotoProviderError("invalid_output", "The image service returned an unusable image.");
  }
}

