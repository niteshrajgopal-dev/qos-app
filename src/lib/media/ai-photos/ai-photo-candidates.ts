/**
 * Reserves one generation for a product inside the caller's tenant
 * transaction, which must already hold the tenant AI photo lock. The spend
 * record (an ai_generated asset) is created before any provider call, so the
 * daily limit cannot be overshot by concurrent requests and failures still
 * count. In queued_worker mode the ai_photo.async spend is admitted and the
 * job enqueued in the same transaction, so admitted work and its job commit
 * together or not at all.
 */
async function reserveAiPhotoInTx(
  tx: DbTransaction,
  caller: AiPhotoCaller,
  menuPublicId: string,
  product: MenuProduct,
  context: ReserveContext,
): Promise<Reservation> {
  const { config, now } = context;
  const mediaConfig = readMediaConfig();

  const [open] = await tx
    .select()
    .from(catalogueMediaAssets)
    .where(
      and(
        eq(catalogueMediaAssets.tenantId, caller.tenantId),
        eq(catalogueMediaAssets.productId, product.id),
        eq(catalogueMediaAssets.sourceProvenance, "ai_generated"),
        inArray(catalogueMediaAssets.status, ["pending_upload", "uploaded"]),
      ),
    )
    .orderBy(desc(catalogueMediaAssets.createdAt))
    .limit(1);

  if (open?.status === "uploaded") {
    return { kind: "existing", asset: open };
  }
  let abandoned: MediaAsset | null = null;
  if (open?.status === "pending_upload") {
    if (metadataOf(open).executionMode === "queued_worker") {
      // A worker may hold queued work, so age alone never abandons it, and the
      // same request is never recreated under another mode.
      const cancelled =
        isStaleQueuedRequest(open, config, now()) &&
        (await cancelStaleQueuedRequestInTx(tx, caller.tenantId, open, actorOf(caller)));
      if (!cancelled) {
        return { kind: "in_progress" };
      }
    } else if (now().getTime() < open.createdAt.getTime() + config.requestTimeoutMs + 60_000) {
      return { kind: "in_progress" };
    } else {
      abandoned = open;
    }
  }

  const used = await countAttemptsInWindow(tx, caller.tenantId, new Date(now().getTime() - QUOTA_WINDOW_MS));
  if (used >= config.dailyLimitPerTenant) {
    return { kind: "daily_limit_reached" };
  }

  const prompt = buildAiPhotoPrompt(product.context);
  const metadata: GenerationMetadata = {
    schema: AI_PHOTO_METADATA_SCHEMA,
    provider: config.provider,
    model: config.provider === "mock" ? "mock" : config.model,
    quality: config.quality,
    promptVersion: AI_PHOTO_PROMPT_VERSION,
    prompt,
    contextSha256: aiPhotoContextSha256(product.context),
    menuPublicId,
    requestedBySubject: caller.subject,
    requestedAt: now().toISOString(),
    executionMode: config.executionMode,
  };

  const grant = await createProductImageUploadGrantInTx(tx, caller.tenantId, product.publicId, {
    expectedByteSize: mediaConfig.maxUploadBytes,
    expectedContentType: "image/jpeg",
    sourceProvenance: "ai_generated",
    generationMetadata: metadata,
    altTextEn: `AI-generated image of ${product.context.displayName}`,
  });

  let spendReservationPublicId: string | null = null;
  if (config.executionMode === "queued_worker") {
    if (!context.spendPolicy) {
      throw new Error("Queued AI photos need a spend policy.");
    }
    const { reservation } = await reserveAiSpend(
      tx,
      {
        tenantId: caller.tenantId,
        path: AI_PHOTO_SPEND_PATH,
        provider: AI_PHOTO_SPEND_PROVIDER,
        subjectType: AI_PHOTO_SPEND_SUBJECT,
        subjectPublicId: grant.assetPublicId,
        units: 1,
        requestedBy: actorOf(caller),
      },
      { policy: context.spendPolicy, now: now() },
    );
    spendReservationPublicId = reservation.publicId;
    await tx
      .update(catalogueMediaAssets)
      .set({ generationMetadata: { ...metadata, spendReservationPublicId } })
      .where(eq(catalogueMediaAssets.id, grant.assetId));
    await enqueueAiJobInTx(tx, {
      tenantId: caller.tenantId,
      jobKind: AI_PHOTO_JOB_KIND,
      mediaAssetId: grant.assetId,
      now: now(),
    });
  }

  // An abandoned synchronous reservation (the request died mid-call) is closed out honestly.
  if (abandoned) {
    await tx
      .update(catalogueMediaAssets)
      .set({
        status: "failed",
        failureReason: "Generation did not finish.",
        generationMetadata: { ...metadataOf(abandoned), failureCode: "abandoned" },
        updatedAt: new Date(),
      })
      .where(eq(catalogueMediaAssets.id, abandoned.id));
  }

  await recordTenantAuditEventInTx(tx, {
    tenantId: caller.tenantId,
    actorSubject: caller.subject,
    actorClass: auditActorClassFromStaffRole(caller.membership.role),
    action: "catalogue.media.ai_photo_requested",
    entityType: "catalogue_media_asset",
    entityPublicId: grant.assetPublicId,
    changeSummary: {
      productPublicId: product.publicId,
      menuPublicId,
      model: config.model,
      quality: config.quality,
      executionMode: config.executionMode,
      ...(spendReservationPublicId ? { spendReservationPublicId } : {}),
      usedToday: used + 1,
      dailyLimit: config.dailyLimitPerTenant,
    },
  });

  const [asset] = await tx
    .select()
    .from(catalogueMediaAssets)
    .where(eq(catalogueMediaAssets.id, grant.assetId))
    .limit(1);
  return { kind: "reserved", asset: asset!, grantToken: grant.grantToken, prompt };
}

function requireGenerationAvailable(config: AiPhotoConfig, options: ServiceOptions) {
  const reason = resolveAvailability(config, options);
  if (reason === "spend_policy_unset") {
    throw new AiPhotoError(
      "spend_policy_unset",
      "AI photos are waiting for a spend policy. Ask your QOS operator to configure it.",
      409,
    );
  }
  if (reason) {
    throw new AiPhotoError("ai_photos_unavailable", "AI photos are not available for this business.", 409);
  }
}

function spendRefusal(error: unknown): never {
  if (error instanceof AiSpendAdmissionError) {
    throw new AiPhotoError(error.code, error.message, error.status);
  }
  throw error;
}

/**
 * Generates one reviewable candidate for a product on the menu. In `sync`
 * mode the provider is called inside this request; in `queued_worker` mode
 * the request is only admitted and the AI worker generates it. Either way the
 * candidate lands in private quarantine; nothing is attached or public until
 * an administrator accepts it.
 */
export async function generateMenuAiPhoto(
  db: DbClient,
  caller: AiPhotoCaller,
  input: { menuPublicId: string; productPublicId: string },
  options: ServiceOptions = {},
): Promise<GenerateAiPhotoResult> {
  const config = options.config ?? readAiPhotoConfig();
  const now = options.now ?? (() => new Date());
  requireAdministrator(caller);
  requireGenerationAvailable(config, options);
  const queued = config.executionMode === "queued_worker";
  const spendPolicy = queued ? (options.spendPolicy ?? readAiSpendPolicy()) : null;

  const reserved = await withTenantContext(db, caller.tenantId, async (tx) => {
    await assertMenuLocationAccess(tx, caller.tenantId, caller.membership, input.menuPublicId);
    await lockTenantAiPhotos(tx, caller.tenantId);
    const product = await requireMenuProduct(tx, caller.tenantId, input.menuPublicId, input.productPublicId);
    return reserveAiPhotoInTx(tx, caller, input.menuPublicId, product, { config, now, spendPolicy });
  }).catch(spendRefusal);

  const view = (asset: MediaAsset) =>
    toCandidateView(caller.tenantId, input.menuPublicId, input.productPublicId, asset);

  switch (reserved.kind) {
    case "existing":
      return { candidate: view(reserved.asset), created: false, queued: false };
    case "in_progress":
      throw new AiPhotoError("generation_in_progress", IN_PROGRESS_MESSAGE, 409);
    case "daily_limit_reached":
      throw new AiPhotoError("daily_limit_reached", dailyLimitMessage(config), 429);
  }
  if (queued) {
    return { candidate: view(reserved.asset), created: true, queued: true };
  }

  const asset = reserved.asset;
  let bytes: Buffer;
  let usage: AiPhotoUsage | null = null;
  try {
    const provider = options.provider ?? getAiPhotoProvider(config);
    const result = await provider.generate({ prompt: reserved.prompt, requestId: asset.publicId });
    usage = result.usage;
    bytes = await normalizeGeneratedImage(result.bytes);
  } catch (error) {
    const failure = providerFailure(error);
    console.warn("AI photo generation failed", {
      tenantId: caller.tenantId,
      assetPublicId: asset.publicId,
      failureCode: failure.failureCode,
      providerOutcome: failure.providerOutcome,
      ...failure.providerDiagnostics,
    });
    const failed = await markGenerationFailed(db, caller, asset.id, failure);
    if (!failed) {
      throw error;
    }
    return { candidate: view(failed), created: true, queued: false };
  }

  try {
    await ingestProductImageUpload(db, caller.tenantId, input.productPublicId, reserved.grantToken, bytes);
  } catch {
    const failed = await markGenerationFailed(db, caller, asset.id, {
      failureCode: "storage_failed",
      message: "The generated image could not be stored.",
    });
    return { candidate: view(failed!), created: true, queued: false };
  }

  const stored = await recordAiPhotoCompletion(db, caller.tenantId, asset.id, { usage, completedAt: now() });
  return { candidate: view(stored), created: true, queued: false };
}

/** What a provider (or output normalisation) failure proves, as recorded on the asset. */
export function providerFailure(error: unknown): AiPhotoFailure & { providerOutcome: ProviderOutcome } {
  if (error instanceof AiPhotoProviderError) {
    return {
      failureCode: error.code,
      message: error.message,
      providerOutcome: error.outcome,
      providerDiagnostics: error.diagnostics,
    };
  }
  return {
    failureCode: "provider_error",
    message: "The image service could not generate this photo.",
    providerOutcome: "submission_unknown",
  };
}

/** Records completion details on a stored candidate. Must run after the image was ingested. */
export async function recordAiPhotoCompletionInTx(
  tx: DbTransaction,
  tenantId: string,
  assetId: string,
  input: { usage: AiPhotoUsage | null; completedAt: Date },
) {
  const [asset] = await tx
    .select()
    .from(catalogueMediaAssets)
    .where(and(eq(catalogueMediaAssets.tenantId, tenantId), eq(catalogueMediaAssets.id, assetId)))
    .limit(1)
    .for("update");
  const [updated] = await tx
    .update(catalogueMediaAssets)
    .set({
      generationMetadata: {
        ...metadataOf(asset!),
        completedAt: input.completedAt.toISOString(),
        usage: input.usage,
      },
      updatedAt: new Date(),
    })
    .where(eq(catalogueMediaAssets.id, assetId))
    .returning();
  return updated!;
}

function recordAiPhotoCompletion(
  db: DbClient,
  tenantId: string,
  assetId: string,
  input: { usage: AiPhotoUsage | null; completedAt: Date },
) {
  return withTenantContext(db, tenantId, (tx) => recordAiPhotoCompletionInTx(tx, tenantId, assetId, input));
}

export type AiPhotoBatchOutcome =
  | "queued"
  | "existing_candidate"
  | "in_progress"
  | "daily_limit_reached"
  | "product_not_in_menu"
  | AiSpendAdmissionErrorCode;

export type AiPhotoBatchItem = {
  productPublicId: string;
  outcome: AiPhotoBatchOutcome;
  candidate: AiPhotoCandidateView | null;
  message: string | null;
};

/**
 * Admits a batch for the AI worker in one transaction under the tenant lock.
 * Each item is admitted on its own savepoint: what fits is queued, and every
 * item reports what happened to it. Only available in queued_worker mode.
 */
export async function queueMenuAiPhotoBatch(
  db: DbClient,
  caller: AiPhotoCaller,
  input: { menuPublicId: string; productPublicIds: readonly string[] },
  options: ServiceOptions = {},
): Promise<{ items: AiPhotoBatchItem[] }> {
  const config = options.config ?? readAiPhotoConfig();
  const now = options.now ?? (() => new Date());
  requireAdministrator(caller);
  if (config.executionMode !== "queued_worker") {
    throw new AiPhotoError("batch_unavailable", "Batch generation is not enabled for this environment.", 409);
  }
  requireGenerationAvailable(config, options);
  const productPublicIds = [...new Set(input.productPublicIds)];
  if (productPublicIds.length === 0 || productPublicIds.length > AI_PHOTO_MAX_BATCH) {
    throw new AiPhotoError(
      "invalid_batch",
      `Choose between 1 and ${AI_PHOTO_MAX_BATCH} items to generate.`,
      400,
    );
  }
  const spendPolicy = options.spendPolicy ?? readAiSpendPolicy();

  return withTenantContext(db, caller.tenantId, async (tx) => {
    await assertMenuLocationAccess(tx, caller.tenantId, caller.membership, input.menuPublicId);
    await lockTenantAiPhotos(tx, caller.tenantId);
    const products = await loadMenuProducts(tx, caller.tenantId, input.menuPublicId, productPublicIds);

    const items: AiPhotoBatchItem[] = [];
    for (const productPublicId of productPublicIds) {
      const item = (outcome: AiPhotoBatchOutcome, candidate: MediaAsset | null, message: string | null) =>
        items.push({
          productPublicId,
          outcome,
          candidate: candidate
            ? toCandidateView(caller.tenantId, input.menuPublicId, productPublicId, candidate)
            : null,
          message,
        });
      const product = products.get(productPublicId);
      if (!product) {
        item("product_not_in_menu", null, "This item is not on the menu.");
        continue;
      }
      try {
        const reserved = await tx.transaction((savepoint) =>
          reserveAiPhotoInTx(savepoint, caller, input.menuPublicId, product, { config, now, spendPolicy }),
        );
        switch (reserved.kind) {
          case "existing":
            item("existing_candidate", reserved.asset, null);
            break;
          case "in_progress":
            item("in_progress", null, IN_PROGRESS_MESSAGE);
            break;
          case "daily_limit_reached":
            item("daily_limit_reached", null, dailyLimitMessage(config));
            break;
          case "reserved":
            item("queued", reserved.asset, null);
            break;
        }
      } catch (error) {
        if (!(error instanceof AiSpendAdmissionError)) {
          throw error;
        }
        item(error.code, null, error.message);
      }
    }
    return { items };
  });
}

async function loadCandidate(
  tx: DbTransaction,
  tenantId: string,
  assetPublicId: string,
  options: { lock: boolean },
) {
  const query = tx
    .select()
    .from(catalogueMediaAssets)
    .where(
      and(
        eq(catalogueMediaAssets.tenantId, tenantId),
        eq(catalogueMediaAssets.publicId, assetPublicId),
        eq(catalogueMediaAssets.sourceProvenance, "ai_generated"),
      ),
    )
    .limit(1);
  const [asset] = options.lock ? await query.for("update") : await query;
  if (!asset) {
    throw new AiPhotoError("candidate_not_found", "AI photo not found.", 404);
  }

  const [product] = await tx
    .select({ publicId: catalogueProducts.publicId })
    .from(catalogueProducts)
    .where(and(eq(catalogueProducts.tenantId, tenantId), eq(catalogueProducts.id, asset.productId)))
    .limit(1);
  if (!product) {
    throw new AiPhotoError("candidate_not_found", "AI photo not found.", 404);
  }
  return { asset, productPublicId: product.publicId };
}

export type AcceptAiPhotoInput = {
  menuPublicId: string;
  assetPublicId: string;
  /** Staff confirmed the image fairly represents the item. Required. */
  accuracyConfirmed: boolean;
  /** Required when the item already has an approved photo. */
  replaceExisting?: boolean;
};

/**
 * Accepts a pending candidate through the normal derivative pipeline and
 * attaches it as the draft product's primary photo. Publishing the menu is a
 * separate action, so nothing goes live here.
 */
export async function acceptMenuAiPhoto(
  db: DbClient,
  caller: AiPhotoCaller,
  input: AcceptAiPhotoInput,
  options: ServiceOptions = {},
): Promise<AiPhotoCandidateView> {
  requireAdministrator(caller);
  const now = options.now ?? (() => new Date());

  return withTenantContext(db, caller.tenantId, async (tx) => {
    await assertMenuLocationAccess(tx, caller.tenantId, caller.membership, input.menuPublicId);
    const { asset, productPublicId } = await loadCandidate(tx, caller.tenantId, input.assetPublicId, { lock: true });
    const product = await requireMenuProduct(tx, caller.tenantId, input.menuPublicId, productPublicId);

    if (asset.status === "approved") {
      return toCandidateView(caller.tenantId, input.menuPublicId, productPublicId, asset);
    }
    if (asset.status !== "uploaded") {
      throw new AiPhotoError("candidate_not_reviewable", "This AI photo can no longer be accepted.", 409);
    }
    if (!input.accuracyConfirmed) {
      throw new AiPhotoError(
        "accuracy_review_required",
        "Confirm the image fairly represents the item before accepting it.",
        400,
      );
    }

    const metadata = metadataOf(asset);
    if (metadata.contextSha256 !== aiPhotoContextSha256(product.context)) {
      throw new AiPhotoError(
        "stale_candidate",
        "The item's name or description changed after this image was generated. Generate a new one.",
        409,
      );
    }

    const [lockedProduct] = await tx
      .select({ primaryMediaAssetId: catalogueProducts.primaryMediaAssetId })
      .from(catalogueProducts)
      .where(eq(catalogueProducts.id, product.id))
      .limit(1)
      .for("update");
    const existingThumbnails = await getApprovedThumbnailPublicIdsForProducts(tx, caller.tenantId, [
      { id: product.id, primaryMediaAssetId: lockedProduct?.primaryMediaAssetId ?? null },
    ]);
    const hasApprovedPhoto = existingThumbnails.has(product.id);
    if (hasApprovedPhoto && !input.replaceExisting) {
      throw new AiPhotoError(
        "existing_photo",
        "This item already has an approved photo. Confirm you want to replace it.",
        409,
      );
    }

    let replacedAssetPublicId: string | null = null;
    if (hasApprovedPhoto && lockedProduct?.primaryMediaAssetId) {
      const [replaced] = await tx
        .select({ publicId: catalogueMediaAssets.publicId })
        .from(catalogueMediaAssets)
        .where(eq(catalogueMediaAssets.id, lockedProduct.primaryMediaAssetId))
        .limit(1);
      replacedAssetPublicId = replaced?.publicId ?? null;
    }

    await processProductImageInTx(tx, caller.tenantId, productPublicId, asset.publicId, caller.subject);

    const [accepted] = await tx
      .update(catalogueMediaAssets)
      .set({
        generationMetadata: {
          ...metadata,
          review: {
            decision: "accepted",
            decidedBySubject: caller.subject,
            decidedAt: now().toISOString(),
            accuracyConfirmed: true,
            replacedAssetPublicId,
          },
        },
        updatedAt: new Date(),
      })
      .where(eq(catalogueMediaAssets.id, asset.id))
      .returning();

    await recordTenantAuditEventInTx(tx, {
      tenantId: caller.tenantId,
      actorSubject: caller.subject,
      actorClass: auditActorClassFromStaffRole(caller.membership.role),
      action: "catalogue.media.ai_photo_accepted",
      entityType: "catalogue_media_asset",
      entityPublicId: asset.publicId,
      changeSummary: { productPublicId, replacedAssetPublicId },
    });

    return toCandidateView(caller.tenantId, input.menuPublicId, productPublicId, accepted);
  });
}

/** Rejects a pending candidate. The product's current photo is untouched. */
export async function rejectMenuAiPhoto(
  db: DbClient,
  caller: AiPhotoCaller,
  input: { menuPublicId: string; assetPublicId: string },
  options: ServiceOptions = {},
): Promise<AiPhotoCandidateView> {
  const now = options.now ?? (() => new Date());

  return withTenantContext(db, caller.tenantId, async (tx) => {
    await assertMenuLocationAccess(tx, caller.tenantId, caller.membership, input.menuPublicId);
    const { asset, productPublicId } = await loadCandidate(tx, caller.tenantId, input.assetPublicId, { lock: true });
    await requireMenuProduct(tx, caller.tenantId, input.menuPublicId, productPublicId);

    if (asset.status === "rejected") {
      return toCandidateView(caller.tenantId, input.menuPublicId, productPublicId, asset);
    }
    if (asset.status !== "uploaded") {
      throw new AiPhotoError("candidate_not_reviewable", "This AI photo can no longer be rejected.", 409);
    }

    const [rejected] = await tx
      .update(catalogueMediaAssets)
      .set({
        status: "rejected",
        generationMetadata: {
          ...metadataOf(asset),
          review: {
            decision: "rejected",
            decidedBySubject: caller.subject,
            decidedAt: now().toISOString(),
          },
        },
        updatedAt: new Date(),
      })
      .where(eq(catalogueMediaAssets.id, asset.id))
      .returning();

    await recordTenantAuditEventInTx(tx, {
      tenantId: caller.tenantId,
      actorSubject: caller.subject,
      actorClass: auditActorClassFromStaffRole(caller.membership.role),
      action: "catalogue.media.ai_photo_rejected",
      entityType: "catalogue_media_asset",
      entityPublicId: asset.publicId,
      changeSummary: { productPublicId },
    });

    return toCandidateView(caller.tenantId, input.menuPublicId, productPublicId, rejected);
  });
}

/** Staff-only preview of a pending candidate from private quarantine storage. */
export async function readMenuAiPhotoPreview(
  db: DbClient,
  caller: AiPhotoCaller,
  input: { menuPublicId: string; assetPublicId: string },
) {
  const path = await withTenantContext(db, caller.tenantId, async (tx) => {
    await assertMenuLocationAccess(tx, caller.tenantId, caller.membership, input.menuPublicId);
    const { asset, productPublicId } = await loadCandidate(tx, caller.tenantId, input.assetPublicId, { lock: false });
    await requireMenuProduct(tx, caller.tenantId, input.menuPublicId, productPublicId);
    if (asset.status !== "uploaded") {
      throw new AiPhotoError("candidate_not_found", "AI photo not found.", 404);
    }
    const [grant] = await tx
      .select({ privateStoragePath: catalogueMediaUploadGrants.privateStoragePath })
      .from(catalogueMediaUploadGrants)
      .where(
        and(
          eq(catalogueMediaUploadGrants.tenantId, caller.tenantId),
          eq(catalogueMediaUploadGrants.assetId, asset.id),
          eq(catalogueMediaUploadGrants.status, "used"),
        ),
      )
      .limit(1);
    if (!grant) {
      throw new AiPhotoError("candidate_not_found", "AI photo not found.", 404);
    }
    return grant.privateStoragePath;
  });

  return { bytes: await getMediaStorage().readPrivate(path), contentType: "image/jpeg" };
}
